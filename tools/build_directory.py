"""Validate data/directory.yaml and render DIRECTORY.md from it.

    python tools/build_directory.py          # write DIRECTORY.md
    python tools/build_directory.py --check  # CI: fail if invalid or DIRECTORY.md is stale

Needs PyYAML (pip install pyyaml).
"""
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "directory.yaml"
OUT = ROOT / "DIRECTORY.md"

KINDS = {"mod", "fork", "decomp-port", "official", "emulator-netplay", "framework", "gap"}
STATUSES = {"playable", "partial", "alpha", "prototype", "abandoned", "official", "none", "unknown"}
QA = {"none", "community-reports", "automated", "verified-playthrough"}
NETWORKING = {"direct-ip", "vpn-needed", "steam-relay", "dedicated-server", "hosted-relay", "lan", "unknown", ""}
SCOPE_KEYS = ("players_visible", "story", "enemies", "world_state", "items")
REQUIRED = ("game", "project", "kind", "status", "qa", "sources", "checked")

QA_BADGE = {
    "verified-playthrough": "verified playthrough",
    "automated": "automated tests",
    "community-reports": "player reports",
    "none": "untested",
}
STATUS_ORDER = ["playable", "official", "partial", "alpha", "prototype", "abandoned", "unknown", "none"]


def normalize_yaml(value):
    """Keep YAML 1.1 yes/no and true/false from leaking into the catalogue."""
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, list):
        return [normalize_yaml(v) for v in value]
    if isinstance(value, dict):
        return {k: normalize_yaml(v) for k, v in value.items()}
    return value


def load_entries(path=DATA):
    return normalize_yaml(yaml.safe_load(path.read_text(encoding="utf-8"))) or []


def errors_for(i, e):
    errs = []
    where = f"entry {i} ({e.get('game', '?')} / {e.get('project', '?')})"
    for k in REQUIRED:
        if k not in e or e[k] in (None, "", []):
            if not (k == "sources" and e.get("kind") == "gap" and e.get("searched")):
                errs.append(f"{where}: missing {k}")
    if e.get("kind") not in KINDS:
        errs.append(f"{where}: kind must be one of {sorted(KINDS)}")
    if e.get("status") not in STATUSES:
        errs.append(f"{where}: status must be one of {sorted(STATUSES)}")
    if e.get("qa") not in QA:
        errs.append(f"{where}: qa must be one of {sorted(QA)}")
    if str(e.get("networking", "")) not in NETWORKING:
        errs.append(f"{where}: networking must be one of {sorted(NETWORKING - {''})}")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(e.get("checked", ""))):
        errs.append(f"{where}: checked must be YYYY-MM-DD")
    for s in e.get("sources") or []:
        if not str(s).startswith("http"):
            errs.append(f"{where}: source is not a URL: {s}")
    for field in ("notes", "project", "game"):
        if "\u2014" in str(e.get(field, "")):
            errs.append(f"{where}: no em dashes please ({field})")
    return errs


def cell(v):
    return str(v if v not in (None, "") else "?").replace("|", "/").replace("\n", " ")


def scope(e):
    s = e.get("coop_scope") or {}
    parts = [f"{k.replace('_', ' ')}: {s[k]}" for k in SCOPE_KEYS if k in s]
    return ", ".join(parts) or "?"


def link(e):
    name = cell(e["project"])
    return f"[{name}]({e['url']})" if e.get("url") else name


def render(entries):
    by_status = Counter(e["status"] for e in entries if e["kind"] != "gap")
    gaps = [e for e in entries if e["kind"] == "gap"]
    projects = [e for e in entries if e["kind"] != "gap"]
    games = len({e["game"] for e in entries})
    lines = [
        "# Co-op directory",
        "",
        "<!-- Generated by tools/build_directory.py from data/directory.yaml. Edit the YAML, not this file. -->",
        "",
        f"{len(projects)} co-op projects and {len(gaps)} open gaps across {games} games. "
        "Status counts: " + ", ".join(f"{s} {by_status[s]}" for s in STATUS_ORDER if by_status[s]) + ".",
        "",
        "**QA** is the column that matters: it says how the claims were checked. "
        "See [data/SCHEMA.md](data/SCHEMA.md). Found something wrong or new? "
        "Edit `data/directory.yaml` and open a pull request, or let your agent do it (see [AGENTS.md](AGENTS.md)).",
        "",
        "## Projects",
        "",
        "| Game | Year | Engine | Project | Kind | Status | What is shared | Players | Net | QA | Last activity |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for e in sorted(projects, key=lambda e: (str(e["game"]).lower(), STATUS_ORDER.index(e["status"]))):
        lines.append(
            f"| {cell(e['game'])} | {cell(e.get('year'))} | {cell(e.get('engine'))} | {link(e)} | {e['kind']} | "
            f"{e['status']} | {cell(scope(e))} | {cell(e.get('players'))} | {cell(e.get('networking'))} | "
            f"{QA_BADGE[e['qa']]} | {cell(e.get('last_activity'))} |"
        )
    lines += [
        "",
        "## Open gaps",
        "",
        "Loved single-player games where no co-op project was found. Searched sources are in the YAML. "
        "If you find one, replace the gap entry with a real one.",
        "",
        "| Game | Year | Engine | Notes |",
        "|---|---|---|---|",
    ]
    for e in sorted(gaps, key=lambda e: str(e["game"]).lower()):
        lines.append(f"| {cell(e['game'])} | {cell(e.get('year'))} | {cell(e.get('engine'))} | {cell(e.get('notes'))} |")
    lines.append("")
    return "\n".join(lines)


def main():
    entries = load_entries()
    errs = [m for i, e in enumerate(entries) for m in errors_for(i, e)]
    seen = Counter((str(e.get("game")).lower(), str(e.get("project")).lower()) for e in entries)
    errs += [f"duplicate entry: {g} / {p}" for (g, p), n in seen.items() if n > 1]
    if errs:
        print("\n".join(errs))
        sys.exit(1)
    text = render(entries)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("DIRECTORY.md is out of date: run python tools/build_directory.py")
            sys.exit(1)
        print(f"OK: {len(entries)} entries")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.name}: {len(entries)} entries")


if __name__ == "__main__":
    main()
