"""Auto-test generation: turn a shrunk fixture into a ready-to-run regression test.

Emits, into the chosen directory (default tools/flight/regress):
  <name>.json    the shrunk fixture, with "expect": {"converges": true} (the test passes once the bug is fixed)
  <name>.cmake   an add_test() line so a ctest case runs your replay program on the fixture
and the generic runner `python -I tools/flight/regress.py <dir> --replay-cmd "..."` runs every fixture in a dir.
A "cofr-trace-1" fixture (from_failure.py) replays in process through trace_replay.py, so it gets no .cmake file.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import trace_replay as TR  # noqa: E402

CMAKE_TEMPLATE = """# generated by tools/flight/gentest.py from a shrunk flight record; do not edit by hand
# Bug it guards against: {sig}
# Steps: {n}. The test passes when the replay program converges (exit code 0) on this fixture.
add_test(NAME cofr_{name}
         COMMAND $<TARGET_FILE:{target}> {flag}${{CMAKE_CURRENT_LIST_DIR}}/{name}.json)
"""


def safe_name(s):
    s = re.sub(r"[^a-z0-9_]+", "_", s.lower()).strip("_")
    return s[:48] or "case"


def generate(shrunk, name, out_dir, target="replay_tool", flag="", expect=None):
    """`target` is the CMake target of your replay program, `flag` the arguments that go before the fixture path, e.g. "--replay ".
    `expect` replaces the default expectation: from_failure.py cases pin recorded evidence of a failure, so they expect divergence."""
    name = safe_name(name)
    info = shrunk.get("shrunk") or {}
    sig = info.get("signature") or "unknown"
    fx = dict(shrunk)
    fx["expect"] = dict(expect) if expect else {"converges": True, "bug_signature": sig}
    os.makedirs(out_dir, exist_ok=True)
    jp = os.path.join(out_dir, name + ".json")
    cp = os.path.join(out_dir, name + ".cmake")
    with open(jp, "w") as f:
        json.dump(fx, f, indent=1, sort_keys=True)
        f.write("\n")
    if fx.get("format") == TR.FORMAT:
        return [jp]
    key = info.get("list_key") or ("ops" if "ops" in fx and "steps" not in fx else "steps")
    with open(cp, "w") as f:
        f.write(CMAKE_TEMPLATE.format(sig=sig.replace("\n", " "), n=len(fx.get(key, [])), name=name, target=target, flag=flag))
    return [jp, cp]
